export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function loc(l: Localized, lang: Lang): string {
  return l[lang] ?? l.en;
}

export type T = (key: StringKey, vars?: Record<string, string | number>) => string;

export const LangContext = createContext<{ lang: Lang; t: T }>({
  lang: 'en',
  t: (k, v) => translate('en', k, v),
});

export const useI18n = () => useContext(LangContext);

export function fmtDuration(min: number, t: T): string {
  if (min < 60) return `${Math.round(min)} ${t('min')}`;
  const h = Math.floor(min / 60);
  const m = Math.round(min % 60);
  return m ? `${h} ${t('hShort')} ${m} ${t('min')}` : `${h} ${t('hShort')}`;
}

export function fmtDist(m: number): string {
  return m < 1000 ? `${Math.round(m / 10) * 10} m` : `${(m / 1000).toFixed(1)} km`;
}
